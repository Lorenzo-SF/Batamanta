#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_get_app_name_is_compiled() {
        let app = GENERATED_APP_NAME;
        assert!(!app.is_empty());
    }

    #[test]
    fn test_instance_id_is_compiled_and_is_uuid() {
        let id = GENERATED_INSTANCE_ID;
        assert!(!id.is_empty(), "INSTANCE_ID must be baked at build time");
        assert!(
            uuid::Uuid::parse_str(id).is_ok(),
            "INSTANCE_ID must parse as UUID v4, got: {}",
            id
        );
    }

    #[test]
    fn test_extract_dir_uses_instance_id() {
        let dir = extract_dir();
        let path_str = dir.to_string_lossy();
        assert!(path_str.contains(GENERATED_INSTANCE_ID));
        assert!(path_str.starts_with("/tmp/"));
        assert!(path_str.contains("batamanta-"));
    }

    #[test]
    fn test_payload_exists() {
        let bytes = include_bytes!(concat!(env!("OUT_DIR"), "/payload.tar.zst"));
        assert!(bytes.len() > 100, "Payload seems too small");
    }

    // ------------------------------------------------------------------
    // resolve_dispatch/0 — needs to be tested by mocking env vars at runtime.
    // We test the pieces separately using a unit-level approach.
    // ------------------------------------------------------------------

    #[test]
    fn test_resolve_dispatch_legacy_when_env_var_unset() {
        // Without env vars set, resolve_dispatch returns Legacy (no env var
        // means no alive-mode request — feature defaults to off).
        // Note: this test depends on the test environment not having the
        // per-binary env var set. In CI, that's true.
        // SAFETY: env::remove_var is unsafe in recent Rust; skip if needed.
        let var = GENERATED_BEAM_ALIVE_VAR;
        let saved = env::var(var).ok();
        env::remove_var(var);

        let decision = resolve_dispatch();
        // Could be either Legacy (default_ms==0) or NoKeeperAvailable
        // (default_ms>0). Both are valid "not legacy fallback" outcomes.
        // Just verify it's not KeeperDispatched (impossible in Phase 3).
        assert_ne!(decision, DispatchDecision::KeeperDispatched);

        if let Some(v) = saved {
            env::set_var(var, v);
        }
    }
}
